-- ============================================================================
--  02_log_schema.sql — 감사 로그 스키마
--
--  왜 게임 스키마와 나누는가 —
--    같은 MySQL 인스턴스의 「다른 스키마」다. 다른 서버가 아니다.
--    그게 핵심이다: 트랜잭션은 커넥션 단위라, 같은 인스턴스면
--    `minigame_log.trade_log` 로 한정자만 붙여도 **거래와 같은 트랜잭션 안에** 남는다.
--    아이템이 움직인 것과 그 기록이 함께 확정되거나 함께 없던 일이 된다.
--
--    서버를 물리적으로 나누는 순간 그 원자성이 사라진다. 그때는 outbox 가 필요하고,
--      outbox 는 다시 멱등성 키를 딸고 온다.
--
--    지금 나눠 두는 값어치는 「오늘의 이득」이 아니다 —
--      스키마명이 이미 갈라져 있으면 나중에 물리 분리할 때
--      **질의를 한 줄도 안 고치고** 커넥션 라우팅만 바꾸면 된다.
--      그리고 백업·보존 정책을 스키마 단위로 따로 걸 수 있다.
--
--  실행 방법 (관리자 계정으로 한 번만)
--    mysql -u root -p < 02_log_schema.sql
--
--  00_account.sql 을 먼저 실행할 것. 계정과 권한이 거기서 만들어진다.
-- ============================================================================

CREATE DATABASE IF NOT EXISTS minigame_log
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

USE minigame_log;

-- ---------------------------------------------------------------------------
--  trade_log — 성사된 거래만 남는다
--
--  「성사된 것만」이 의도다. 실패한 거래(잔량 부족 등)는 롤백되므로
--    같은 트랜잭션 안에 넣으면 그 기록도 같이 사라진다. 트랜잭션 밖에서 남기면
--    이번엔 원자성이 없어져서 「기록은 있는데 거래는 없었다」가 가능해진다.
--    ⇒ 역할을 나눈다 — 성공은 여기(증거), 실패는 텍스트 로그(정황).
--
--    판단 기준은 「이 기록이 없으면 무엇을 못 하는가」다.
--      성공 기록이 없으면 → 아이템이 움직인 사실을 증명 못 한다
--      실패 기록이 없으면 → 불편할 뿐, 아이템은 그대로다
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS trade_log (
    id          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,

    -- 상계 「전」 원본이다. 유저가 화면에서 본 것과 같다.
    --   상계 후를 남기면 「200을 5개 주고 3개 받았다」가 「2개를 줬다」로 기록되어,
    --   CS 응대 때 유저가 본 것과 기록이 어긋난다.
    --   상계 결과는 이 값에서 코드로 재현되므로 따로 안 남긴다.
    a_player    BIGINT UNSIGNED NOT NULL,
    a_item      INT UNSIGNED    NOT NULL,
    a_count     INT UNSIGNED    NOT NULL,
    b_player    BIGINT UNSIGNED NOT NULL,
    b_item      INT UNSIGNED    NOT NULL,
    b_count     INT UNSIGNED    NOT NULL,

    -- 어느 존의 몇 번째 거래였나. 서버 텍스트 로그의 [TRADE] tid= 와 대조할 때 쓴다.
    -- 유일하지 않다 — trade_id 는 존마다 1부터 세고 재시작하면 다시 1이다.
    --   그래서 이 둘은 「키」가 아니라 「대조용 표식」이다.
    --   요청 ID 기반 멱등성이 필요해지는 것은 서버를 물리적으로 나눌 때다.
    zone_id     INT UNSIGNED    NOT NULL,
    trade_id    INT UNSIGNED    NOT NULL,

    -- 밀리초까지 둔다. 초 단위면 같은 초에 일어난 두 거래의 앞뒤를 못 가린다.
    -- (그래도 확실한 순서는 id 다 — created_at 은 사람이 읽는 값이다)
    created_at  DATETIME(3)     NOT NULL DEFAULT CURRENT_TIMESTAMP(3),

    PRIMARY KEY (id),

    -- 인덱스가 둘인 이유 — 한 플레이어가 a 일 수도 b 일 수도 있다.
    --   「이 사람의 최근 거래」가 CS 조회의 대부분이고, 한쪽만 걸면 절반을 놓친다.
    --   id 가 시간순이라 정렬 키로 그대로 쓴다 — created_at 인덱스는 안 만든다.
    --     시간 범위 조회도 id 범위로 바꿔서 할 수 있다.
    KEY ix_a (a_player, id),
    KEY ix_b (b_player, id)

    -- 외래키를 「일부러 안 건다」.
    --   inventory 는 ON DELETE CASCADE 다 — 플레이어가 지워지면 인벤토리도 지워진다.
    --   로그는 그 반대여야 한다. 지워지면 감사 자체가 무의미해진다.
    --   ⇒ 로그는 참조가 아니라 「그 시점의 스냅샷」이다. FK 는 그 성격과 안 맞는다.
    --   그래서 없는 player_id 가 남을 수 있다. 그게 맞다 — 탈퇴한 유저의
    --     과거 거래도 조사 대상이다.
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------------
--  보존 정책이 없다 — 이 테이블은 계속 는다.
--    파티셔닝이나 아카이빙 배치가 필요해지는 시점이 온다.
--    지금 넣지 않은 이유는 근거가 없어서다: 아직 아무것도 안 쌓였고,
--    보존 기간을 정하는 것은 서버가 아니라 운영·법무의 판단이다.
--    ⇒ 「나중에 할 일」이 아니라 「그쪽이 정해 줘야 할 일」이라 비워 뒀다.
-- ---------------------------------------------------------------------------

SHOW TABLES FROM minigame_log;
